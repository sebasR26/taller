public class objLibreria {
    //ejercicios #3
    String name;
    String autor;
    double precio;

    public objLibreria(String name, String autor, double precio) {
        this.name = name;
        this.autor = autor;
        this.precio = precio;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getAutor() {
        return autor;
    }

    public void setAutor(String autor) {
        this.autor = autor;
    }

    public double getPrecio() {
        return precio;
    }

    public void setPrecio(double precio) {
        this.precio = precio;
    }

    

    
}
