public class objasiento {
    int fila;
    int numero;
    double precio;
    public objasiento(int fila, int numero, double precio) {
        this.fila = fila;
        this.numero = numero;
        this.precio = precio;
    }
    public int getFila() {
        return fila;
    }
    public void setFila(int fila) {
        this.fila = fila;
    }
    public int getNumero() {
        return numero;
    }
    public void setNumero(int numero) {
        this.numero = numero;
    }
    public double getPrecio() {
        return precio;
    }
    public void setPrecio(double precio) {
        this.precio = precio;
    }

    
    
}
